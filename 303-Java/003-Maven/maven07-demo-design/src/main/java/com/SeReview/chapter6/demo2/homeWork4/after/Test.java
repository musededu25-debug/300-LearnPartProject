package com.SeReview.chapter6.demo2.homeWork4.after;

/**
 * 练习 4 · 目标输出与真实输出（已跑通，一字不差）
 *
 * Child.print, value=0
 *
 * ─────────────────────────────────────────────────────────
 * 为什么是 0 而不是 100？（用 1.5 的六步说，不说"字段还没初始化"这种废话）
 *
 * new Child() 的六步实际走法：
 *   ① 父类静态块        —— 没有
 *   ② 子类静态块        —— 没有
 *   ③ 父类实例初始化块 / 父类字段赋值 —— Father 没有字段，跳过
 *   ④ 父类构造方法体    —— ★ 就是这一步出的问题
 *          Father() 里调 print()。print 是【虚方法】，实际对象是 Child，
 *          于是动态绑定，跑到了 Child.print()。
 *          它要读 value —— 可 value 属于【第 ⑤ 步】，此刻根本还没执行。
 *          所以读到的只能是默认值 0。
 *   ⑤ 子类实例初始化块 / 子类字段赋值 —— int value = 100; 在这一刻才执行
 *          ⚠️ 但 Child.print() 在第 ④ 步就已经跑完了，这 100 白给了。
 *   ⑥ 子类构造方法体    —— Child 没写构造方法，编译器插入 Child() { super(); }，构造体是空的
 *
 * 一句话回答「卡在第几步、被谁抢先了」：
 *   ★ 子类字段初始化排在【第 ⑤ 步】，父类构造体在【第 ④ 步】就把它抢先了。
 *     动态绑定让方法去了子类，可子类的「家当」还没搬进来 —— 方法先到、字段后到。
 *
 * ─────────────────────────────────────────────────────────
 * 怎么避免（三条任选）：
 *   · 把 print() 声明成 private 或 final —— 子类就重写不了，动态绑定失效
 *   · 别在构造方法里调用可被重写的方法（《Effective Java》的正解）
 *   · 必须初始化，就挪到 init() 方法或工厂方法里，不在构造阶段碰
 *
 * 🔗 复习 1 的联系：你的练习 1 里 `int a = initIntA();` + `public int initIntA()`
 *    就是同一个形态。只要在 Son 里重写 initIntA()，这里发生的事会原样发生在你那份代码上。
 *    （练习 1 的修正版里我把那两个方法改成了 private，就是为了躲开这个坑。）
 */
