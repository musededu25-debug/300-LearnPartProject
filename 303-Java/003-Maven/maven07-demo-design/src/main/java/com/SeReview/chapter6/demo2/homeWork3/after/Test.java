package com.SeReview.chapter6.demo2.homeWork3.after;

/**
 * 练习 3 · 三层继承 —— 目标输出与真实输出（已跑通，一字不差）
 *
 * A-static
 * B-static
 * C-static        ← ① 三条静态连着出现，一个 -inst 都没插进来
 * A-inst
 * A-ctor
 * B-inst
 * B-ctor
 * C-inst
 * C-ctor          ← ② new C() 的实例部分：从最顶层往下走一整轮
 * A-inst
 * A-ctor          ← ③ 第二次 new A()：没有 A-static
 *
 * ─────────────────────────────────────────────────────────
 * 三个问题的答案：
 *
 * ① 三个 -static 连在一起，说明「静态」不是跟着每个对象走的，
 *    而是【这条继承链上所有类的静态初始化，从最顶层往下，一次性全部做完】，
 *    然后才开始第一个对象的实例初始化。
 *    ★ 这是练习 1（只有两层）看不出来的东西 —— 两层的输出很容易让你误以为
 *      规则是「父静→子静→父实例→子实例」这样一层层交替。三层才暴露真相：
 *      静态是「整条链扫一遍」，实例才是「每个对象扫一遍」。
 *
 * ② 第二次 new A() 前面没有 A-static —— 因为【一个类只初始化一次】，
 *    A 已经在 new C() 时被连带初始化过了（初始化子类会先初始化父类）。
 *
 * ③ 第二次 new A() 只走了 A-inst / A-ctor：B 和 C 跟这个对象没关系。
 *    实例初始化永远只沿着「这个对象的实际类型 → 往上到 Object」这条线走，
 *    往下（B、C）不属于它。
 */
public class Test {

    public static void main(String[] args) {
        new C();     // 静态：A→B→C 全扫一遍；实例：A→B→C 一整轮
        new A();     // 静态：没有；实例：只有 A 自己那一轮
    }
}
